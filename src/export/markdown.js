/**
 * Exports remediation tasks into human-readable Markdown.
 */

export function exportTasksToMarkdown(workspaceData) {
  const { tasks = [], observations = [], sourceSummary = {} } = workspaceData;

  const lines = [
    `# Accessibility Remediation Plan`,
    ``,
    `*Generated by Open Accessibility Workbench on ${new Date().toLocaleDateString()}*`,
    ``,
    `## Executive Summary`,
    `- **Total Scanner Observations**: ${observations.length}`,
    `- **Actionable Remediation Tasks**: ${tasks.length}`,
    `- **Source Scanner**: ${sourceSummary.system || 'N/A'} (Scan: ${sourceSummary.scanId || 'N/A'})`,
    ``,
    `---`,
    ``,
    `## Remediation Tasks`,
    ``
  ];

  for (const task of tasks) {
    lines.push(`### [${task.id}] ${task.title}`);
    lines.push(`- **Urgency**: ${task.urgency.toUpperCase()} | **Leverage**: ${task.leverage.toUpperCase()}`);
    lines.push(`- **WCAG Criteria**: ${task.wcag.join(', ') || 'N/A'}`);
    lines.push(`- **Primary Role**: ${task.roles?.primary || 'Front-End Development'}`);
    if (task.roles?.secondary?.length) {
      lines.push(`- **Supporting Roles**: ${task.roles.secondary.join(', ')}`);
    }
    lines.push(`- **Affected Pages**: ${task.metrics.affectedPagesCount} (${task.metrics.observationCount} occurrences)`);
    if (task.componentHypothesis) {
      lines.push(`- **Component Hypothesis**: ${task.componentHypothesis.name} (${task.componentHypothesis.confidence} confidence)`);
    }
    lines.push(``);
    lines.push(`#### Problem & Systemic Rationale`);
    lines.push(task.blueprint.problem);
    lines.push(``);
    lines.push(task.blueprint.systemicRationale);
    lines.push(``);
    lines.push(`#### What Needs to Change`);
    lines.push(task.blueprint.whatNeedsToChange);
    lines.push(``);
    if (task.blueprint.humanDecisionsRequired?.length) {
      lines.push(`#### Human Decisions Required`);
      for (const dec of task.blueprint.humanDecisionsRequired) {
        lines.push(`- [ ] ${dec}`);
      }
      lines.push(``);
    }
    if (task.blueprint.targetMarkup) {
      lines.push(`#### Target Markup / Guidance`);
      lines.push('```html');
      lines.push(task.blueprint.targetMarkup);
      lines.push('```');
      lines.push(``);
    }
    lines.push(`#### Verification Steps`);
    for (const step of task.blueprint.verificationSteps) {
      lines.push(`1. ${step}`);
    }
    lines.push(``);
    lines.push(`---`);
    lines.push(``);
  }

  return lines.join('\n');
}
